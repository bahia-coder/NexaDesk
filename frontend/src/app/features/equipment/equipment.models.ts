/** Same rules as the API (EquipmentService.validateDates); `today` is yyyy-MM-dd in the company zone. */
export function equipmentDatesError(
  acquisitionDate: string | null,
  warrantyEndDate: string | null,
  today: string,
): string | null {
  if (acquisitionDate && acquisitionDate > today) {
    return 'La date d’acquisition ne peut pas être future.';
  }
  if (acquisitionDate && warrantyEndDate && warrantyEndDate < acquisitionDate) {
    return 'La fin de garantie doit suivre la date d’acquisition.';
  }
  return null;
}

export type EquipmentAction =
  | 'ASSIGN'
  | 'UNASSIGN'
  | 'SEND_TO_REPAIR'
  | 'BACK_IN_USE'
  | 'BACK_TO_STOCK'
  | 'DEPLOY_SHARED'
  | 'EDIT'
  | 'RETIRE';

/**
 * What the role can do with the device in its current state: the API's rules (EquipmentService), so the page
 * only shows buttons that will be accepted. The API still checks everything.
 */
export function equipmentActions(equipment: Equipment, role: Role): EquipmentAction[] {
  if (role === 'EMPLOYEE' || equipment.status === 'RETIRED') {
    return [];
  }
  const admin = role === 'ADMIN';
  const held = equipment.assignedUser !== null;
  const repair = equipment.status === 'IN_REPAIR';
  const actions: EquipmentAction[] = [];
  if (admin && !repair) {
    actions.push('ASSIGN');
    if (held) {
      actions.push('UNASSIGN');
    }
  }
  if (!repair) {
    actions.push('SEND_TO_REPAIR');
  } else if (held || equipment.location) {
    actions.push('BACK_IN_USE');
  }
  if (!held && equipment.status !== 'IN_STOCK') {
    actions.push('BACK_TO_STOCK');
  }
  if (!held && equipment.status === 'IN_STOCK' && equipment.location) {
    actions.push('DEPLOY_SHARED');
  }
  if (admin) {
    actions.push('EDIT', 'RETIRE');
  }
  return actions;
}
