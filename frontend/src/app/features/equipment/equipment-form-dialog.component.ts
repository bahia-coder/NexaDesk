import { DIALOG_DATA, DialogRef } from '@angular/cdk/dialog';
import { ChangeDetectionStrategy, Component, inject, signal } from '@angular/core';
import { NonNullableFormBuilder, ReactiveFormsModule, Validators } from '@angular/forms';

import { companyTimeZone } from '../../core/format/time';
import { toApiProblem } from '../../core/http/api-error';
import { SpinnerComponent } from '../../shared/ui/spinner.component';
import { nowInZone } from '../settings/zoned-time';
import {
  EQUIPMENT_TYPES,
  EQUIPMENT_TYPE_LABELS,
  Equipment,
  EquipmentFields,
  EquipmentType,
  equipmentDatesError,
} from './equipment.models';
import { EquipmentService } from './equipment.service';

export interface EquipmentFormDialogData {
  /** Null to add a device. */
  equipment: Equipment | null;
}

/** Add or edit a device (admins). The inventory code is generated by the API. */
@Component({
  selector: 'nx-equipment-form-dialog',
  imports: [ReactiveFormsModule, SpinnerComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    <form class="dialog" [formGroup]="form" (ngSubmit)="save()" novalidate>
      <h2 id="nx-equipment-form-title" class="card__title">
        {{ data.equipment ? 'Modifier ' + data.equipment.inventoryCode : 'Nouvel équipement' }}
      </h2>
      <div class="grid">
        <label class="field">
          <span class="field__label">Nom *</span>
          <input
            class="input"
            formControlName="name"
            maxlength="120"
            placeholder="ex. Portable de Sara Idrissi"
            cdkFocusInitial
            [attr.aria-invalid]="invalid('name')"
          />
          @if (invalid('name')) {
            <span class="field__error">Le nom est obligatoire.</span>
          }
        </label>
        <label class="field">
          <span class="field__label">Type *</span>
          <select class="select" formControlName="type">
            @for (t of types; track t) {
              <option [value]="t">{{ typeLabels[t] }}</option>
            }
          </select>
        </label>
      </div>
      <div class="grid">
        <label class="field">
          <span class="field__label">Marque</span>
          <input class="input" formControlName="brand" maxlength="60" />
        </label>
        <label class="field">
          <span class="field__label">Modèle</span>
          <input class="input" formControlName="model" maxlength="80" />
        </label>
      </div>
      <label class="field">
        <span class="field__label">Numéro de série</span>
        <input
          class="input mono"
          formControlName="serialNumber"
          maxlength="80"
          autocomplete="off"
          [attr.aria-invalid]="!!serverErrors()['serialNumber']"
        />
        @if (serverErrors()['serialNumber']; as message) {
          <span class="field__error">{{ message }}</span>
        } @else {
          <span class="field__hint">Unique dans le parc ; enregistré en majuscules.</span>
        }
      </label>
      <div class="grid">
        <label class="field">
          <span class="field__label">Date d’acquisition</span>
          <input class="input" type="date" formControlName="acquisitionDate" [max]="today" />
        </label>
        <label class="field">
          <span class="field__label">Fin de garantie</span>
          <input class="input" type="date" formControlName="warrantyEndDate" />
        </label>
      </div>
      <label class="field">
        <span class="field__label">Emplacement</span>
        <input
          class="input"
          formControlName="location"
          maxlength="120"
          placeholder="ex. 2e étage – salle copieurs"
        />
        <span class="field__hint"
          >Obligatoire pour un équipement partagé (imprimante, serveur…).</span
        >
      </label>
      <label class="field">
        <span class="field__label">Notes</span>
        <textarea class="input" rows="3" formControlName="notes" maxlength="1000"></textarea>
      </label>
      @if (error(); as message) {
        <p class="field__error" role="alert">{{ message }}</p>
      }
      <div class="actions">
        <button type="button" class="btn btn--secondary" (click)="ref.close()">Annuler</button>
        <button type="submit" class="btn btn--primary" [disabled]="saving()">
          @if (saving()) {
            <nx-spinner />
          }
          {{ data.equipment ? 'Enregistrer' : 'Ajouter au parc' }}
        </button>
      </div>
    </form>
  `,
  styles: `
    .dialog {
      display: flex;
      flex-direction: column;
      gap: var(--space-4);
      width: 600px;
      max-width: 100%;
      max-height: calc(100vh - 48px);
      overflow-y: auto;
      padding: var(--space-6);
      border-radius: var(--radius-lg);
      background: var(--color-surface-raised);
      box-shadow: var(--shadow-lg);
    }

    .grid {
      display: grid;
      grid-template-columns: 1fr 1fr;
      gap: var(--space-4);

      @media (width < 640px) {
        grid-template-columns: 1fr;
      }
    }

    .actions {
      display: flex;
      justify-content: flex-end;
      gap: var(--space-2);
    }
  `,
})
export class EquipmentFormDialogComponent {
  protected readonly data = inject<EquipmentFormDialogData>(DIALOG_DATA);
  protected readonly ref = inject<DialogRef<Equipment>>(DialogRef);
  private readonly api = inject(EquipmentService);

  protected readonly types = EQUIPMENT_TYPES;
  protected readonly typeLabels = EQUIPMENT_TYPE_LABELS;
  /** yyyy-MM-dd in the company time zone, as the API checks it. */
  protected readonly today = nowInZone(Date.now(), companyTimeZone()).slice(0, 10);
  protected readonly saving = signal(false);
  protected readonly error = signal<string | null>(null);
  /** Field errors returned by the API (400 VALIDATION_FAILED, 409 serial number already used). */
  protected readonly serverErrors = signal<Record<string, string>>({});

  protected readonly form = inject(NonNullableFormBuilder).group({
    name: [this.data.equipment?.name ?? '', [Validators.required, Validators.maxLength(120)]],
    type: [this.data.equipment?.type ?? ('LAPTOP' as EquipmentType), Validators.required],
    brand: [this.data.equipment?.brand ?? '', Validators.maxLength(60)],
    model: [this.data.equipment?.model ?? '', Validators.maxLength(80)],
    serialNumber: [this.data.equipment?.serialNumber ?? '', Validators.maxLength(80)],
    acquisitionDate: [this.data.equipment?.acquisitionDate ?? ''],
    warrantyEndDate: [this.data.equipment?.warrantyEndDate ?? ''],
    location: [this.data.equipment?.location ?? '', Validators.maxLength(120)],
    notes: [this.data.equipment?.notes ?? '', Validators.maxLength(1000)],
  });

  protected save(): void {
    if (this.form.invalid || this.saving()) {
      this.form.markAllAsTouched();
      return;
    }
    const v = this.form.getRawValue();
    const fields: EquipmentFields = {
      name: v.name.trim(),
      type: v.type,
      brand: v.brand.trim() || null,
      model: v.model.trim() || null,
      serialNumber: v.serialNumber.trim() || null,
      acquisitionDate: v.acquisitionDate || null,
      warrantyEndDate: v.warrantyEndDate || null,
      location: v.location.trim() || null,
      notes: v.notes.trim() || null,
    };
    const datesError = equipmentDatesError(
      fields.acquisitionDate,
      fields.warrantyEndDate,
      this.today,
    );
    if (datesError) {
      this.error.set(datesError);
      return;
    }
    this.saving.set(true);
    this.error.set(null);
    this.serverErrors.set({});
    const id = this.data.equipment?.id;
    (id ? this.api.update(id, fields) : this.api.create(fields)).subscribe({
      next: (saved) => this.ref.close(saved),
      error: (error: unknown) => {
        this.saving.set(false);
        const problem = toApiProblem(error);
        if (problem.code === 'SERIAL_NUMBER_ALREADY_USED') {
          this.serverErrors.set({ serialNumber: problem.detail });
        } else {
          this.serverErrors.set(
            Object.fromEntries(problem.errors.map((e) => [e.field, e.message])),
          );
          this.error.set(problem.detail);
        }
      },
    });
  }

  protected invalid(name: 'name'): boolean {
    const control = this.form.controls[name];
    return control.invalid && control.touched;
  }
}
