package com.nexadesk.knowledge;

import com.nexadesk.category.TicketCategory;
import com.nexadesk.common.BaseEntity;
import com.nexadesk.ticket.Ticket;
import com.nexadesk.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Knowledge base article. The full-text {@code search_vector} column is generated by PostgreSQL and only used by
 * native queries ({@link KnowledgeSearch}), so it is not mapped. View and vote counters are changed with targeted
 * SQL updates: reading an article never conflicts with an author editing it.
 */
@Entity
@Table(name = "knowledge_articles")
@Getter
@Setter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class KnowledgeArticle extends BaseEntity {

    @Column(nullable = false, length = 150)
    private String title;

    @Column(nullable = false, length = 500)
    private String summary;

    @Column(nullable = false, columnDefinition = "text")
    private String content;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "category_id")
    private TicketCategory category;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "author_id")
    @Setter(AccessLevel.NONE)
    private User author;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_ticket_id", updatable = false)
    @Setter(AccessLevel.NONE)
    private Ticket sourceTicket;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    @Setter(AccessLevel.NONE)
    private ArticleStatus status = ArticleStatus.DRAFT;

    @Column(name = "view_count", nullable = false, insertable = false, updatable = false)
    @Setter(AccessLevel.NONE)
    private int viewCount;

    @Column(name = "helpful_count", nullable = false, insertable = false, updatable = false)
    @Setter(AccessLevel.NONE)
    private int helpfulCount;

    @Column(name = "published_at")
    @Setter(AccessLevel.NONE)
    private Instant publishedAt;

    @Version
    @Setter(AccessLevel.NONE)
    private int version;

    public KnowledgeArticle(String title, String summary, String content, TicketCategory category, User author,
                            Ticket sourceTicket) {
        this.title = title;
        this.summary = summary;
        this.content = content;
        this.category = category;
        this.author = author;
        this.sourceTicket = sourceTicket;
    }

    /** The first publication date is kept when an archived article is published again. */
    public void publish(Instant now) {
        status = ArticleStatus.PUBLISHED;
        if (publishedAt == null) {
            publishedAt = now;
        }
    }

    public void archive() {
        status = ArticleStatus.ARCHIVED;
    }

    public boolean isWrittenBy(Long userId) {
        return author.getId().equals(userId);
    }
}
