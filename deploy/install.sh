#!/usr/bin/env bash
# Installs and starts NexaDesk on a fresh Ubuntu server (22.04 / 24.04, x86_64 or ARM), behind HTTPS.
#
# Run from the project directory (the extracted archive), as a user allowed to use sudo:
#   bash deploy/install.sh --email vous@exemple.fr            # real installation, your administrator account
#   bash deploy/install.sh --email vous@exemple.fr --demo     # + the demonstration data and accounts
#   bash deploy/install.sh --email ... --domain helpdesk.mon-domaine.fr
#
# Without --domain, the address is <public-ip>.sslip.io (free, no registration; it resolves to the server).
# Re-running the script keeps the existing .env (secrets and data are never regenerated) and redeploys.
set -euo pipefail

EMAIL=""
DOMAIN=""
DEMO=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --email) EMAIL="${2:-}"; shift 2 ;;
    --domain) DOMAIN="${2:-}"; shift 2 ;;
    --demo) DEMO=true; shift ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) echo "Option inconnue : $1 (voir --help)" >&2; exit 1 ;;
  esac
done

cd "$(dirname "$0")/.."
if [[ ! -f docker-compose.yml || ! -f deploy/docker-compose.prod.yml ]]; then
  echo "Lancez ce script depuis le dossier du projet NexaDesk." >&2
  exit 1
fi

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }

# --- 1. Docker (Ubuntu packages: no third-party script) ---------------------------------------------------
if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  step "Installation de Docker"
  sudo apt-get update -y
  sudo apt-get install -y docker.io docker-compose-v2 openssl curl
  sudo systemctl enable --now docker
fi
DOCKER="docker"
if ! docker info >/dev/null 2>&1; then
  DOCKER="sudo docker"
  sudo usermod -aG docker "$USER" || true
fi

# --- 2. Firewall: Oracle's Ubuntu images reject everything but SSH in iptables ----------------------------
step "Ouverture des ports 80 et 443"
for port in 80 443; do
  if ! sudo iptables -C INPUT -p tcp --dport "$port" -j ACCEPT 2>/dev/null; then
    sudo iptables -I INPUT 1 -p tcp --dport "$port" -j ACCEPT
  fi
done
if ! sudo iptables -C INPUT -p udp --dport 443 -j ACCEPT 2>/dev/null; then
  sudo iptables -I INPUT 1 -p udp --dport 443 -j ACCEPT
fi
if command -v netfilter-persistent >/dev/null 2>&1; then
  sudo netfilter-persistent save >/dev/null
fi

# --- 3. Configuration (.env, created once) -----------------------------------------------------------------
ADMIN_PASSWORD=""
if [[ -f .env ]]; then
  step "Fichier .env existant conservé"
  DOMAIN="$(grep -E '^DOMAIN=' .env | cut -d= -f2-)"
else
  if [[ -z "$EMAIL" ]]; then
    echo "Première installation : indiquez l'e-mail de l'administrateur avec --email." >&2
    exit 1
  fi
  if [[ -z "$DOMAIN" ]]; then
    PUBLIC_IP="$(curl -fsS https://api.ipify.org)"
    DOMAIN="${PUBLIC_IP//./-}.sslip.io"
  fi
  step "Création du fichier .env (secrets aléatoires)"
  # Temporary administrator password: letters, digits and a special character, changed at the first sign-in.
  ADMIN_PASSWORD="Nx-$(openssl rand -hex 6)-$(openssl rand -hex 3 | tr 'a-f' 'A-F')7!"
  PROFILES="prod"
  if [[ "$DEMO" == true ]]; then
    PROFILES="prod,demo"
  fi
  umask 077
  cat > .env <<EOF
# Generated by deploy/install.sh on $(date -u +%Y-%m-%d). Never commit this file.
DOMAIN=${DOMAIN}
POSTGRES_DB=nexadesk
POSTGRES_USER=nexadesk
POSTGRES_PASSWORD=$(openssl rand -hex 24)
SPRING_PROFILES_ACTIVE=${PROFILES}
APP_TIMEZONE=Europe/Paris
JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
APP_ALLOWED_ORIGINS=https://${DOMAIN}
AUTH_COOKIE_SECURE=true
BOOTSTRAP_ADMIN_EMAIL=${EMAIL}
BOOTSTRAP_ADMIN_PASSWORD=${ADMIN_PASSWORD}
BOOTSTRAP_ADMIN_FIRST_NAME=Administrateur
BOOTSTRAP_ADMIN_LAST_NAME=NexaDesk
AI_MODE=heuristic
AI_PROVIDER=anthropic
AI_API_KEY=
AI_BASE_URL=
AI_MODEL=
EOF
fi

# --- 4. Build and start ------------------------------------------------------------------------------------
step "Construction et démarrage (plusieurs minutes la première fois)"
COMPOSE=($DOCKER compose -f docker-compose.yml -f deploy/docker-compose.prod.yml)
"${COMPOSE[@]}" up -d --build

step "Attente du démarrage de l'API et du certificat HTTPS"
ONLINE=false
for _ in $(seq 1 60); do
  if curl -fsS "https://${DOMAIN}/actuator/health" 2>/dev/null | grep -q '"UP"'; then
    ONLINE=true
    break
  fi
  sleep 5
done
"${COMPOSE[@]}" ps
if [[ "$ONLINE" != true ]]; then
  cat >&2 <<EOF

L'application ne répond pas encore sur https://${DOMAIN}. Vérifiez :
  - que les ports 80 et 443 (TCP) sont ouverts dans la "Security List" du réseau de la VM (console Oracle) ;
  - les journaux : ${DOCKER} compose -f docker-compose.yml -f deploy/docker-compose.prod.yml logs caddy backend
EOF
  exit 1
fi

printf '\n\033[1;32mNexaDesk est en ligne : https://%s\033[0m\n' "$DOMAIN"
if [[ -n "$ADMIN_PASSWORD" ]]; then
  printf 'Administrateur : %s\nMot de passe temporaire : %s\n' "$EMAIL" "$ADMIN_PASSWORD"
  printf '(À changer à la première connexion ; il reste aussi dans .env, lisible par vous seul.)\n'
fi
if [[ "$DEMO" == true ]]; then
  printf 'Mode démo : les comptes de démonstration sont proposés sur la page de connexion.\n'
fi
